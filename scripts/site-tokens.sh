#!/bin/bash
# The website's design tokens, generated from the app's: scripts/site-tokens.sh [mode] [--tokens FILE]
#
#   scripts/site-tokens.sh                 # print the CSS block
#   scripts/site-tokens.sh --check [HTML]  # exit 1 (with a diff) if HTML's block differs
#   scripts/site-tokens.sh --write [HTML]  # replace HTML's block with a fresh one
#
# Reads every `public static let name: Type = literal` inside `public enum DesignTokens`
# (Sources/VisorCore/DesignTokens.swift) and prints a :root block of --v-* variables
# between /* tokens:begin */ and /* tokens:end */. HTML defaults to docs/index.html.
# Exits 2 on a token line it can't read, so a new shape fails instead of vanishing.
set -euo pipefail
cd "$(dirname "$0")/.."

MODE=print
HTML=docs/index.html
TOKENS=Sources/VisorCore/DesignTokens.swift
while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) MODE=check ;;
    --write) MODE=write ;;
    --tokens) shift; TOKENS="${1:?--tokens needs a file}" ;;
    -h|--help) sed -n '2,11p' "$0"; exit 0 ;;
    -*) echo "site-tokens: unknown option $1" >&2; exit 2 ;;
    *) HTML="$1" ;;
  esac
  shift
done
[[ -f "$TOKENS" ]] || { echo "site-tokens: no $TOKENS" >&2; exit 2; }

BEGIN='  /* tokens:begin */'
NOTE='  /* The app'"'"'s design tokens, generated by scripts/site-tokens.sh from Sources/VisorCore/DesignTokens.swift.
     Do not edit here: change the Swift file, then run scripts/site-tokens.sh --write. */'
END='  /* tokens:end */'

block() {
  echo "$BEGIN"
  echo "$NOTE"
  echo "  :root {"
  awk -v file="$TOKENS" '
    function kebab(s,   out, i, c) {
      out = ""
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c ~ /[A-Z]/) out = out "-" tolower(c); else out = out c
      }
      return out
    }
    function fail(msg) { printf "%s:%d: %s\n", file, NR, msg > "/dev/stderr"; bad = 1; exit 2 }
    /^public enum DesignScale/ { exit }
    /^[[:space:]]*\/\// { next }
    /^public enum DesignTokens[[:space:]]*\{/ { inside = 1; next }
    !inside { next }
    /^[[:space:]]*public enum [A-Za-z]+[[:space:]]*\{/ {
      group = $3
      if (group !~ /^(Palette|TypeScale|Radius|Fill|Space|Size)$/) fail("unknown token group " group)
      next
    }
    /static let/ {
      line = $0
      if (!match(line, /public static let [A-Za-z][A-Za-z0-9]*: (UInt32|Double) = [-0-9A-Fa-fx.]+[[:space:]]*$/))
        fail("token line not in the shape `public static let name: Type = literal`")
      if (group == "") fail("token outside a group")
      split(substr(line, RSTART), w, /[[:space:]]+/)
      name = w[4]; sub(/:$/, "", name); type = w[5]; value = w[7]
      if (group == "Palette") {
        if (type != "UInt32" || length(value) != 8 || value !~ /^0x[0-9A-Fa-f]+$/) fail("colour must be UInt32 0xRRGGBB")
        printf "    --v-%s: #%s;\n", kebab(name), toupper(substr(value, 3))
      } else {
        if (type != "Double" || value !~ /^[0-9]+(\.[0-9]+)?$/) fail("size must be a Double literal")
        if (group == "Fill") printf "    --v-fill-%s: rgba(255,255,255,%s);\n", kebab(name), value
        else {
          prefix = (group == "TypeScale") ? "type" : tolower(group)
          printf "    --v-%s-%s: %spx;\n", prefix, kebab(name), value
        }
      }
      count++
      next
    }
    END { if (!bad && count == 0) { printf "%s: no tokens found\n", file > "/dev/stderr"; exit 2 } }
  ' "$TOKENS" || return 2
  echo "  }"
  echo "$END"
}

OUT="$(block)" || exit 2

# The current block in HTML, markers included, or nothing.
current() { awk '/\/\* tokens:begin \*\// { on = 1 } on { print } /\/\* tokens:end \*\// { if (on) exit }' "$1"; }

case "$MODE" in
  print) echo "$OUT" ;;
  check)
    [[ -f "$HTML" ]] || { echo "site-tokens: no $HTML" >&2; exit 2; }
    CUR="$(current "$HTML")"
    if [[ -z "$CUR" ]]; then
      echo "$HTML: no tokens block (run scripts/site-tokens.sh --write)" >&2; exit 1
    fi
    if [[ "$CUR" != "$OUT" ]]; then
      echo "$HTML: tokens block differs from $TOKENS (run scripts/site-tokens.sh --write)" >&2
      diff <(echo "$CUR") <(echo "$OUT") >&2 || true
      exit 1
    fi
    ;;
  write)
    [[ -f "$HTML" ]] || { echo "site-tokens: no $HTML" >&2; exit 2; }
    [[ -n "$(current "$HTML")" ]] || { echo "$HTML: add the /* tokens:begin */ and /* tokens:end */ lines first" >&2; exit 2; }
    TMPF="$(mktemp)"
    BLOCK="$OUT" awk '
      /\/\* tokens:begin \*\// { print ENVIRON["BLOCK"]; skip = 1; next }
      skip && /\/\* tokens:end \*\// { skip = 0; next }
      !skip { print }
    ' "$HTML" > "$TMPF"
    cat "$TMPF" > "$HTML"; rm -f "$TMPF"
    ;;
esac
