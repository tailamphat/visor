#!/bin/bash
# The website's design tokens, generated from the app's: scripts/site-tokens.sh [mode] [HTML] [--tokens FILE] [--parts FILE]
#
#   scripts/site-tokens.sh                 # print the tokens CSS block
#   scripts/site-tokens.sh --check [HTML]  # exit 1 (with a diff) if any of HTML's blocks differs
#   scripts/site-tokens.sh --write [HTML]  # replace HTML's blocks with fresh ones
#
# Blocks, each between /* NAME:begin */ and /* NAME:end */ lines in HTML's style:
#   tokens      required. A :root block of --v-* variables from every `public static let name: Type = literal`
#               inside `public enum DesignTokens` (Sources/VisorCore/DesignTokens.swift). Each colour also gets
#               --v-solid-<name> (the colour as a solid button or badge fill, darkened for white text where needed),
#               --v-on-<name> (its text colour, var(--v-text-primary) or var(--v-surface)) and --v-held-<name> (held),
#               as DesignContrast.solid in Sources/VisorCore/DesignContrast.swift.
#   components  if present. The shared component classes (.v-btn, .v-card, ...) copied from
#               docs/index.html's components block, which is hand-written there (index.html is the source).
#   measures    if present. A :root block of --v-c-<component>-<name> variables from every
#               `public static let` in `public enum DesignComponents` (Sources/VisorCore/DesignComponents.swift):
#               a literal as a plain number (points or a strength), a token (`T.Size.button`) as its var().
#               Also plugin pieces (`enum PluginPieces`, --v-c-plugin-pieces-*) and the colour names plugins
#               may use (`enum PluginColor`, --v-c-plugin-color-<name>: var(--v-<palette>)) from
#               Sources/VisorCore/Plugins/PluginDesign.swift.
#   contrast    if present. A :root block of --v-k-<fill>: <solid fill var> <on-colour var> <ratio>, one per row of the pairing
#               table (`Fill(name: "x", hex: P.y)` lines in Sources/VisorCore/DesignContrast.swift).
# HTML defaults to docs/index.html. Exits 2 on a line it can't read, so a new shape fails instead of vanishing.
set -euo pipefail
cd "$(dirname "$0")/.."

MODE=print
HTML=docs/index.html
TOKENS=Sources/VisorCore/DesignTokens.swift
PARTS=Sources/VisorCore/DesignComponents.swift
PIECES=Sources/VisorCore/Plugins/PluginDesign.swift
CONTRAST=Sources/VisorCore/DesignContrast.swift
SOURCE=docs/index.html
while [[ $# -gt 0 ]]; do
  case "$1" in
    --check) MODE=check ;;
    --write) MODE=write ;;
    --tokens) shift; TOKENS="${1:?--tokens needs a file}" ;;
    --parts) shift; PARTS="${1:?--parts needs a file}" ;;
    -h|--help) sed -n '2,24p' "$0"; exit 0 ;;
    -*) echo "site-tokens: unknown option $1" >&2; exit 2 ;;
    *) HTML="$1" ;;
  esac
  shift
done
[[ -f "$TOKENS" ]] || { echo "site-tokens: no $TOKENS" >&2; exit 2; }

BEGIN='  /* tokens:begin */'
NOTE='  /* The app'"'"'s design tokens, generated by scripts/site-tokens.sh from Sources/VisorCore/DesignTokens.swift.
     Do not edit here: change the Swift file, then run scripts/site-tokens.sh --write. */'
END='  /* tokens:end */'

# WCAG 2 relative luminance of "RRGGBB" and the on-colour (DesignContrast.on), for awk.
WCAG_AWK='
    # How a colour is drawn as a solid fill (DesignContrast.solid): white text on the fill darkened
    # by the smallest 0.5% step that reaches 4.5:1 (at most 27%); black text on the light fills
    # (warning, awake, mint, onPace, stuck) and past 27%. The Design contrast tests hold this to Swift.
    function byte(h, i) { return (index("0123456789ABCDEF", substr(h, i, 1)) - 1) * 16 + index("0123456789ABCDEF", substr(h, i + 1, 1)) - 1 }
    function chan(v,   c) { c = v / 255; return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ^ 2.4 }
    function lum(r, g, b) { return 0.2126 * chan(r) + 0.7152 * chan(g) + 0.0722 * chan(b) }
    function hex2(r, g, b) { return sprintf("%02X%02X%02X", r, g, b) }
    # Sets S_FILL (hex), S_SAME (1 when not darkened), S_WHITE (1 for white text), S_RATIO.
    function solid(name, h,   r, g, b, k, a, dr, dg, db, l) {
      r = byte(h, 1); g = byte(h, 3); b = byte(h, 5)
      if (name !~ /^(warning|awake|mint|onPace|stuck)$/) {
        for (k = 0; k * 0.005 <= 0.27 + 1e-9; k++) {
          a = k * 0.005
          dr = k ? int(r * (1 - a) + 0.5) : r; dg = k ? int(g * (1 - a) + 0.5) : g; db = k ? int(b * (1 - a) + 0.5) : b
          l = lum(dr, dg, db)
          if (1.05 / (l + 0.05) >= 4.5) { S_FILL = hex2(dr, dg, db); S_SAME = (k == 0); S_WHITE = 1; S_RATIO = 1.05 / (l + 0.05); return }
        }
      }
      S_FILL = h; S_SAME = 1; S_WHITE = 0; S_RATIO = (lum(r, g, b) + 0.05) / 0.05
    }
    # The held fill: 25% (1 - CardButton.pressedOpacity) toward white under black text, toward black under white.
    function held(h,   r, g, b, t) {
      r = byte(h, 1); g = byte(h, 3); b = byte(h, 5); t = S_WHITE ? 0 : 255
      return hex2(int(t * 0.25 + r * 0.75 + 0.5), int(t * 0.25 + g * 0.75 + 0.5), int(t * 0.25 + b * 0.75 + 0.5))
    }
'

block() {
  echo "$BEGIN"
  echo "$NOTE"
  echo "  :root {"
  awk -v file="$TOKENS" "$WCAG_AWK"'
    function kebab(s,   out, i, c) {
      out = ""
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c ~ /[A-Z]/) out = out "-" tolower(c); else out = out c
      }
      return out
    }
    function fail(msg) { printf "%s:%d: %s\n", file, NR, msg > "/dev/stderr"; bad = 1; exit 2 }
    function emit(var, value) {
      if (var in seen) fail("two tokens make " var)
      seen[var] = 1
      printf "    %s: %s;\n", var, value
    }
    /^public enum DesignScale/ { exit }
    /^[[:space:]]*\/\// { next }
    /^public enum DesignTokens[[:space:]]*\{/ { inside = 1; next }
    !inside { next }
    /^[[:space:]]*public enum [A-Za-z]+[[:space:]]*\{/ {
      group = $3
      if (group !~ /^(Palette|TypeScale|Radius|Fill|Space|Size)$/) fail("unknown token group " group)
      next
    }
    /^    \}/ { group = ""; next }
    /static let/ {
      line = $0
      if (!match(line, /public static let [A-Za-z][A-Za-z0-9]*: (UInt32|Double) = [-0-9A-Fa-fx.]+[[:space:]]*$/))
        fail("token line not in the shape `public static let name: Type = literal`")
      if (group == "") fail("token outside a group")
      split(substr(line, RSTART), w, /[[:space:]]+/)
      name = w[4]; sub(/:$/, "", name); type = w[5]; value = w[7]
      if (group == "Palette") {
        if (type != "UInt32" || length(value) != 8 || value !~ /^0x[0-9A-Fa-f]+$/) fail("colour must be UInt32 0xRRGGBB")
        emit("--v-" kebab(name), "#" toupper(substr(value, 3)))
        solid(name, toupper(substr(value, 3)))
        ons++; onvar[ons] = "--v-on-" kebab(name); onval[ons] = S_WHITE ? "var(--v-text-primary)" : "var(--v-surface)"
        ons++; onvar[ons] = "--v-solid-" kebab(name); onval[ons] = S_SAME ? "var(--v-" kebab(name) ")" : "#" S_FILL
        ons++; onvar[ons] = "--v-held-" kebab(name); onval[ons] = "#" held(S_FILL)
      } else {
        if (type != "Double" || value !~ /^[0-9]+(\.[0-9]+)?$/) fail("size must be a Double literal")
        if (group == "Fill") emit("--v-fill-" kebab(name), "rgba(255,255,255," value ")")
        else {
          prefix = (group == "TypeScale") ? "type" : tolower(group)
          emit("--v-" prefix "-" kebab(name), value "px")
        }
      }
      count++
      next
    }
    END {
      if (!bad && count == 0) { printf "%s: no tokens found\n", file > "/dev/stderr"; exit 2 }
      if (!bad) for (i = 1; i <= ons; i++) emit(onvar[i], onval[i])
    }
  ' "$TOKENS" || return 2
  echo "  }"
  echo "$END"
}

OUT="$(block)" || exit 2

# The measures block: DesignComponents, then PluginColor names and PluginPieces from PluginDesign.swift.
measures() {
  echo '  /* measures:begin */'
  echo '  /* The shared components'"'"' measurements, generated by scripts/site-tokens.sh from Sources/VisorCore/DesignComponents.swift
     and Sources/VisorCore/Plugins/PluginDesign.swift. Do not edit here: change the Swift file, then run scripts/site-tokens.sh --write on this page. Plain numbers are points or strengths. */'
  echo '  :root {'
  awk -v file="$PARTS" '
    function kebab(s,   out, i, c) {
      out = ""
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c ~ /[A-Z]/) out = out "-" tolower(c); else out = out c
      }
      sub(/^-/, "", out)
      return out
    }
    function fail(msg) { printf "%s:%d: %s\n", file, FNR, msg > "/dev/stderr"; bad = 1; exit 2 }
    # One variable; a /* Group */ line before the first of each group names the Swift enum.
    function emit(grp, var, value) {
      if (var in seen) fail("two measures make " var)
      seen[var] = 1
      if (grp != last) { printf "    /* %s */\n", grp; last = grp }
      printf "    %s: %s;\n", var, value
      count++
    }
    FNR == 1 { file = FILENAME; inside = 0; group = ""; colors = 0; flat = 0; infunc = 0 }
    /^[[:space:]]*\/\// { next }
    /^public enum DesignComponents[[:space:]]*\{/ { inside = 1; next }
    /^public enum PluginPieces[[:space:]]*\{/ { inside = 1; group = "PluginPieces"; flat = 1; next }
    /^public enum PluginColor[^{]*\{/ { colors = 1; next }
    # PluginColor: its declared cases (`case a, b`), then one switch arm per case
    # (`case .a: return p.palette`); any other case line, or a case without an arm, fails.
    colors && /^\}/ {
      colors = 0
      for (d in declared) if (!(d in armed)) fail("PluginColor case " d " has no `case ." d ": return p.<palette>` line")
      next
    }
    colors && /^[[:space:]]*case [A-Za-z]+([[:space:]]*,[[:space:]]*[A-Za-z]+)*[[:space:]]*$/ {
      line = $0; sub(/^[[:space:]]*case[[:space:]]+/, "", line); gsub(/[[:space:]]/, "", line)
      nd = split(line, ds, ","); for (k = 1; k <= nd; k++) declared[ds[k]] = 1
      next
    }
    colors && /^[[:space:]]*case \.[A-Za-z]+: return p\.[A-Za-z]+[[:space:]]*$/ {
      line = $0; sub(/^[[:space:]]*case \./, "", line); split(line, w, /[: ]+/)
      name = w[1]; pal = w[3]; sub(/^p\./, "", pal); armed[name] = 1
      emit("PluginColor", "--v-c-plugin-color-" kebab(name), "var(--v-" kebab(pal) ")")
      next
    }
    colors && /^[[:space:]]*case / { fail("PluginColor case line not in the shape `case a, b` or `case .a: return p.palette`") }
    !inside { next }
    /^\}/ { inside = 0; group = ""; flat = 0; next }
    infunc {
      depth += gsub(/\{/, "{"); depth -= gsub(/\}/, "}")
      if (depth <= 0) infunc = 0
      next
    }
    flat && /static let measurements/ { next }
    !flat && /^    public enum [A-Za-z]+[[:space:]]*\{/ { group = $3; next }
    !flat && /^    \}/ { group = ""; next }
    group != "" && /static func/ {
      depth = gsub(/\{/, "{") - gsub(/\}/, "}")
      if (depth > 0) infunc = 1
      next
    }
    group != "" && /static let/ {
      line = $0
      if (match(line, /public static let [A-Za-z][A-Za-z0-9]*(: Double)? = [0-9]+(\.[0-9]+)?[[:space:]]*$/)) {
        n = split(substr(line, RSTART), w, /[[:space:]]+/)
        name = w[4]; sub(/:$/, "", name); value = w[n]
      } else if (match(line, /public static let [A-Za-z][A-Za-z0-9]* = T\.[A-Za-z]+\.[A-Za-z][A-Za-z0-9]*[[:space:]]*$/)) {
        n = split(substr(line, RSTART), w, /[[:space:]]+/)
        name = w[4]; split(w[6], r, ".")
        if (r[2] == "Palette") value = "var(--v-" kebab(r[3]) ")"
        else if (r[2] == "TypeScale") value = "var(--v-type-" kebab(r[3]) ")"
        else if (r[2] ~ /^(Radius|Fill|Space|Size)$/) value = "var(--v-" tolower(r[2]) "-" kebab(r[3]) ")"
        else fail("unknown token group " r[2])
      } else fail("measure line not in the shape `public static let name = literal` or `= T.Group.name`")
      emit(group, "--v-c-" kebab(group) "-" kebab(name), value)
      next
    }
    END { if (!bad && count == 0) { printf "%s: no measures found\n", file > "/dev/stderr"; exit 2 } }
  ' "$PARTS" "$PIECES" || return 2
  echo '  }'
  echo '  /* measures:end */'
}

# The contrast block: each row of DesignContrast.fills, its on-colour and the ratio.
contrast() {
  [[ -f "$CONTRAST" ]] || { echo "site-tokens: no $CONTRAST" >&2; exit 2; }
  echo '  /* contrast:begin */'
  echo '  /* The contrast pairing table (fill, its on-colour, the ratio), generated by scripts/site-tokens.sh from
     Sources/VisorCore/DesignContrast.swift and the palette. Do not edit here. Text needs 4.5:1, large text and icons 3:1. */'
  echo '  :root {'
  awk "$WCAG_AWK"'
    function kebab(s,   out, i, c) {
      out = ""
      for (i = 1; i <= length(s); i++) {
        c = substr(s, i, 1)
        if (c ~ /[A-Z]/) out = out "-" tolower(c); else out = out c
      }
      return out
    }
    function fail(msg) { printf "%s:%d: %s\n", FILENAME, FNR, msg > "/dev/stderr"; bad = 1; exit 2 }
    FNR == 1 { pass++ }
    pass == 1 && /^public enum DesignScale/ { nextfile }
    pass == 1 && /public static let [A-Za-z][A-Za-z0-9]*: UInt32 = 0x[0-9A-Fa-f]{6}/ {
      split($0, w, /[[:space:]]+/); for (i = 1; i in w; i++) if (w[i] == "let") { name = w[i + 1]; value = w[i + 4] }
      sub(/:$/, "", name); hex[name] = toupper(substr(value, 3)); next
    }
    pass == 2 {
      line = $0
      while (match(line, /Fill\(name: "[A-Za-z]+", hex: P\.[A-Za-z]+\)/)) {
        f = substr(line, RSTART, RLENGTH); line = substr(line, RSTART + RLENGTH)
        split(f, q, "\""); name = q[2]; pal = f; sub(/.*P\./, "", pal); sub(/\)$/, "", pal)
        if (!(pal in hex)) fail("no palette colour " pal)
        if (("--v-k-" kebab(name)) in seen) fail("two rows make --v-k-" kebab(name))
        seen["--v-k-" kebab(name)] = 1
        solid(pal, hex[pal])
        printf "    --v-k-%s: var(--v-solid-%s) var(--v-on-%s) %.2f;\n", kebab(name), kebab(pal), kebab(pal), S_RATIO
        count++
      }
    }
    END { if (!bad && count == 0) { printf "%s: no Fill rows found\n", FILENAME > "/dev/stderr"; exit 2 } }
  ' "$TOKENS" "$CONTRAST" || return 2
  echo '  }'
  echo '  /* contrast:end */'
}

# Each block: exactly one begin line, then exactly one end line after it; anything else stops
# before a read or a write, so a lost end marker can never swallow the page. Returns 1 when
# the file has neither marker.
markers() {
  local f="$1" n="$2" b e
  b="$(grep -c "$n:begin \*/" "$f" || true)"; e="$(grep -c "$n:end \*/" "$f" || true)"
  [[ "$b" == 0 && "$e" == 0 ]] && return 1
  if [[ "$b" != 1 || "$e" != 1 ]] ||
     (( $(grep -n "$n:begin \*/" "$f" | cut -d: -f1) > $(grep -n "$n:end \*/" "$f" | cut -d: -f1) )); then
    echo "$f: needs one /* $n:begin */ line followed by one /* $n:end */ line (found $b begin, $e end)" >&2
    exit 2
  fi
}

# The current block in a file, markers included.
current() { awk -v n="$2" '$0 ~ ("/\\* " n ":begin \\*/") { on = 1 } on { print } $0 ~ ("/\\* " n ":end \\*/") { if (on) exit }' "$1"; }

# The fresh text of a block, markers included.
fresh() {
  case "$2" in
    tokens) echo "$OUT" ;;
    measures) measures ;;
    contrast) contrast ;;
    components)
      [[ -f "$SOURCE" ]] || { echo "site-tokens: no $SOURCE" >&2; exit 2; }
      markers "$SOURCE" components || { echo "$SOURCE: no /* components:begin */ block to copy" >&2; exit 2; }
      current "$SOURCE" components ;;
  esac
}

# Blocks this file carries: tokens always; components (unless the file is their source) and measures if marked.
blocks() {
  echo tokens
  if markers "$1" components && [[ "$1" -ef "$SOURCE" ]]; then :; elif markers "$1" components; then echo components; fi
  if markers "$1" measures; then echo measures; fi
  if markers "$1" contrast; then echo contrast; fi
}

case "$MODE" in
  print) echo "$OUT" ;;
  check)
    [[ -f "$HTML" ]] || { echo "site-tokens: no $HTML" >&2; exit 2; }
    if ! markers "$HTML" tokens; then
      echo "$HTML: no tokens block (run scripts/site-tokens.sh --write)" >&2; exit 1
    fi
    markers "$HTML" components || true; markers "$HTML" measures || true; markers "$HTML" contrast || true
    STATUS=0
    for NAME in $(blocks "$HTML"); do
      NEW="$(fresh "$HTML" "$NAME")" || exit 2
      CUR="$(current "$HTML" "$NAME")"
      if [[ "$CUR" != "$NEW" ]]; then
        case "$NAME" in
          tokens) FROM="$TOKENS" ;; measures) FROM="$PARTS and $PIECES" ;; components) FROM="$SOURCE" ;;
          contrast) FROM="$CONTRAST" ;;
        esac
        echo "$HTML: $NAME block differs from $FROM (run scripts/site-tokens.sh --write $HTML)" >&2
        diff <(echo "$CUR") <(echo "$NEW") >&2 || true
        STATUS=1
      fi
    done
    exit "$STATUS"
    ;;
  write)
    [[ -f "$HTML" ]] || { echo "site-tokens: no $HTML" >&2; exit 2; }
    markers "$HTML" tokens || { echo "$HTML: add the /* tokens:begin */ and /* tokens:end */ lines first" >&2; exit 2; }
    markers "$HTML" components || true; markers "$HTML" measures || true; markers "$HTML" contrast || true
    # Build every block before touching the page, so a block that fails leaves the page as it was.
    TMPF="$(mktemp)"; NEXT="$(mktemp)"
    trap 'rm -f "$TMPF" "$NEXT"' EXIT
    cat "$HTML" > "$TMPF"
    for NAME in $(blocks "$HTML"); do
      NEW="$(fresh "$HTML" "$NAME")" || exit 2
      BLOCK="$NEW" awk -v n="$NAME" '
        $0 ~ ("/\\* " n ":begin \\*/") { print ENVIRON["BLOCK"]; skip = 1; next }
        skip && $0 ~ ("/\\* " n ":end \\*/") { skip = 0; next }
        !skip { print }
      ' "$TMPF" > "$NEXT" || exit 2
      cat "$NEXT" > "$TMPF"
    done
    cat "$TMPF" > "$HTML"
    ;;
esac
