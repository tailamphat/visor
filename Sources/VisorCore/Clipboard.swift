import Foundation

/// Something copied: text, a link, a colour, files or an image.
public struct ClipItem: Codable, Equatable, Identifiable, Sendable {
    public enum Kind: String, Codable, Sendable { case text, link, color, file, image }

    public var id = UUID()
    public var kind: Kind
    /// The text; file paths (one per line) for files; a file name in Visor's folder for images.
    public var content: String
    /// The app it was copied from.
    public var app: String
    public var date: Date
    public var pinned = false

    public init(kind: Kind, content: String, app: String, date: Date) {
        self.kind = kind
        self.content = content
        self.app = app
        self.date = date
    }

    /// Text that is a web address or a colour gets its own kind.
    public static func kind(of text: String) -> Kind {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if parseColor(trimmed) != nil { return .color }
        let lower = trimmed.lowercased()
        if (lower.hasPrefix("http://") || lower.hasPrefix("https://")), !trimmed.contains(" "), !trimmed.contains("\n"),
           URL(string: trimmed)?.host != nil {
            return .link
        }
        return .text
    }

    /// Commands and code read better in monospace: punctuation code uses, or a
    /// shell-like line (a single word followed by flags or paths).
    public var looksLikeCode: Bool {
        guard kind == .text else { return kind == .color }
        let text = title
        if text.contains(where: { "{}();=<>$`|".contains($0) }) { return true }
        let words = text.split(separator: " ")
        if words.contains(where: { $0.hasPrefix("-") || $0.hasPrefix("./") || $0.hasPrefix("/") || $0.hasPrefix("~/") }) { return true }
        return false
    }

    /// Red, green and blue (0-255) for a colour.
    public var colorRGB: [Int]? { kind == .color ? Self.parseColor(content.trimmingCharacters(in: .whitespacesAndNewlines)) : nil }

    /// One line for the list.
    public var title: String {
        let line = content.split(whereSeparator: \.isNewline).first.map(String.init) ?? content
        return line.trimmingCharacters(in: .whitespaces)
    }

    static func parseColor(_ text: String) -> [Int]? {
        if text.hasPrefix("#") {
            let hex = String(text.dropFirst())
            guard [3, 6, 8].contains(hex.count), hex.allSatisfy(\.isHexDigit), let value = UInt64(hex, radix: 16) else { return nil }
            if hex.count == 3 {
                return [(value >> 8) & 0xF, (value >> 4) & 0xF, value & 0xF].map { Int($0 * 17) }
            }
            let rgb = hex.count == 8 ? value >> 8 : value
            return [Int((rgb >> 16) & 0xFF), Int((rgb >> 8) & 0xFF), Int(rgb & 0xFF)]
        }
        let lower = text.lowercased()
        guard lower.hasPrefix("rgb(") || lower.hasPrefix("rgba("), lower.hasSuffix(")"),
              let open = lower.firstIndex(of: "(") else { return nil }
        let parts = lower[lower.index(after: open)..<lower.index(before: lower.endIndex)]
            .split(separator: ",").map { $0.trimmingCharacters(in: .whitespaces) }
        guard parts.count >= 3 else { return nil }
        let rgb = parts.prefix(3).compactMap { Int($0) }
        return rgb.count == 3 && rgb.allSatisfy { (0...255).contains($0) } ? rgb : nil
    }
}

/// The clipboard history, newest first.
public struct ClipHistory: Codable, Equatable, Sendable {
    public private(set) var items: [ClipItem] = []

    /// Kept: the newest 200 unpinned items, none older than 30 days; pinned items always.
    public static let maxItems = 200
    public static let maxAge: TimeInterval = 30 * 86_400

    public init() {}

    /// Pasteboard types apps use to say "don't keep this" (passwords, one-time codes).
    static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public static func shouldRecord(types: [String], app: String?, excluded: Set<String>) -> Bool {
        if types.contains(where: secretTypes.contains) { return false }
        if let app, excluded.contains(app) { return false }
        return true
    }

    /// Adds a copy at the top. Copying something again moves it up, keeping its pin.
    public mutating func add(_ item: ClipItem, now: Date) {
        guard !item.content.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        var item = item
        if let i = items.firstIndex(where: { $0.kind == item.kind && $0.content == item.content }) {
            item.pinned = items[i].pinned
            item.id = items[i].id
            items.remove(at: i)
        }
        items.insert(item, at: 0)
        trim(now: now)
    }

    public mutating func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
    }

    /// Removes an item; the result can undo it.
    public mutating func delete(_ id: UUID) -> Removed? {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return nil }
        return Removed(item: items.remove(at: i), index: i)
    }

    public mutating func restore(_ removed: Removed) {
        guard !items.contains(where: { $0.id == removed.item.id }) else { return }
        items.insert(removed.item, at: min(removed.index, items.count))
    }

    public mutating func clear(keepPinned: Bool) {
        items = keepPinned ? items.filter(\.pinned) : []
    }

    /// Items whose text or app contains the query, ignoring case and accents.
    public func search(_ query: String) -> [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return items }
        let options: String.CompareOptions = [.caseInsensitive, .diacriticInsensitive]
        return items.filter { $0.content.range(of: q, options: options) != nil || $0.app.range(of: q, options: options) != nil }
    }

    /// "Today", "Yesterday", then dates, newest first.
    public static func days(_ items: [ClipItem], now: Date, calendar: Calendar = .current) -> [(title: String, items: [ClipItem])] {
        var groups: [(title: String, items: [ClipItem])] = []
        let today = calendar.startOfDay(for: now)
        for item in items {
            let day = calendar.startOfDay(for: item.date)
            let ago = calendar.dateComponents([.day], from: day, to: today).day ?? 0
            let title: String
            switch ago {
            case ...0: title = "Today"
            case 1: title = "Yesterday"
            default:
                let formatter = DateFormatter()
                formatter.calendar = calendar
                formatter.timeZone = calendar.timeZone
                formatter.setLocalizedDateFormatFromTemplate("EEEEdMMM")
                title = formatter.string(from: day)
            }
            if groups.last?.title == title { groups[groups.count - 1].items.append(item) } else { groups.append((title, [item])) }
        }
        return groups
    }

    private mutating func trim(now: Date) {
        var kept = 0
        items = items.filter { item in
            if item.pinned { return true }
            guard now.timeIntervalSince(item.date) <= Self.maxAge, kept < Self.maxItems else { return false }
            kept += 1
            return true
        }
    }

    /// A deleted item and where it was, for undo.
    public struct Removed: Sendable {
        public var item: ClipItem
        public var index: Int
    }
}
