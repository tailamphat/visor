import Foundation
import Testing
@testable import VisorCore

private let t0 = ISO8601DateFormatter().date(from: "2026-11-01T10:00:00Z")!
private func clip(_ text: String, _ kind: ClipItem.Kind? = nil, app: String = "Notes", at date: Date = t0) -> ClipItem {
    ClipItem(kind: kind ?? ClipItem.kind(of: text), content: text, app: app, date: date)
}

@Suite("Clipboard: what was copied")
struct ClipKindTests {
    @Test("Kinds from copied text", arguments: [
        ("https://github.com/octocat/visor", ClipItem.Kind.link),
        ("#7EE0A0", .color), ("#fff", .color), ("rgb(126, 224, 160)", .color),
        ("Release Acme 0.1.4", .text), ("#hashtag", .text),
    ])
    func kinds(text: String, kind: ClipItem.Kind) {
        #expect(ClipItem.kind(of: text) == kind)
    }

    @Test("Code shows in monospace", arguments: [
        ("swift test --scratch-path .build/tests", true), ("let x = foo(bar)", true), ("{\"a\": 1}", true),
        ("Release Acme 0.1.4 with the new updater", false), ("Meeting notes: Visor naming", false),
    ])
    func code(text: String, isCode: Bool) {
        #expect(clip(text).looksLikeCode == isCode)
    }

    @Test func colorsParse() {
        #expect(clip("#7EE0A0").colorRGB == [126, 224, 160])
        #expect(clip("#fff").colorRGB == [255, 255, 255])
        #expect(clip("rgb(1, 2, 3)").colorRGB == [1, 2, 3])
        #expect(clip("hello").colorRGB == nil)
    }

    @Test func rowsShowOneLine() {
        #expect(clip("first line\nsecond line").title == "first line")
        #expect(clip("   padded  ").title == "padded")
    }
}

@Suite("Clipboard: privacy")
struct ClipPrivacyTests {
    @Test("Secret and temporary copies are never recorded", arguments: [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ])
    func secrets(type: String) {
        #expect(!ClipHistory.shouldRecord(types: ["public.utf8-plain-text", type], app: "com.1password.1password", excluded: []))
    }

    @Test func excludedAppsAreSkipped() {
        #expect(!ClipHistory.shouldRecord(types: ["public.utf8-plain-text"], app: "com.bank.app", excluded: ["com.bank.app"]))
        #expect(ClipHistory.shouldRecord(types: ["public.utf8-plain-text"], app: "com.apple.Notes", excluded: ["com.bank.app"]))
    }
}

@Suite("Clipboard: history")
struct ClipHistoryTests {
    @Test func newestFirst() {
        var h = ClipHistory()
        h.add(clip("a"), now: t0)
        h.add(clip("b", at: t0.addingTimeInterval(1)), now: t0)
        #expect(h.items.map(\.content) == ["b", "a"])
    }

    @Test func copyingAgainMovesToTheTopAndKeepsThePin() throws {
        var h = ClipHistory()
        h.add(clip("a"), now: t0)
        h.add(clip("b", at: t0.addingTimeInterval(1)), now: t0)
        h.togglePin(try #require(h.items.last).id)
        h.add(clip("a", app: "Ghostty", at: t0.addingTimeInterval(2)), now: t0)
        #expect(h.items.map(\.content) == ["a", "b"] && h.items.count == 2)
        #expect(h.items[0].pinned && h.items[0].app == "Ghostty")
    }

    @Test func blankCopiesAreIgnored() {
        var h = ClipHistory()
        h.add(clip("   \n "), now: t0)
        #expect(h.items.isEmpty)
    }

    @Test func deleteAndUndo() throws {
        var h = ClipHistory()
        ["a", "b", "c"].enumerated().forEach { h.add(clip($1, at: t0.addingTimeInterval(Double($0))), now: t0) }
        let b = try #require(h.items.first { $0.content == "b" })
        let deleted = h.delete(b.id)
        let removed = try #require(deleted)
        #expect(h.items.map(\.content) == ["c", "a"])
        h.restore(removed)
        #expect(h.items.map(\.content) == ["c", "b", "a"], "undo puts it back where it was")
    }

    @Test func clearAllKeepsPinsUnlessAsked() throws {
        var h = ClipHistory()
        ["a", "b"].forEach { h.add(clip($0), now: t0) }
        h.togglePin(try #require(h.items.first { $0.content == "a" }).id)
        h.clear(keepPinned: true)
        #expect(h.items.map(\.content) == ["a"])
        h.clear(keepPinned: false)
        #expect(h.items.isEmpty)
    }

    @Test func keepsTwoHundredAndThirtyDaysButAlwaysPins() throws {
        var h = ClipHistory()
        // Copied and pinned 40 days ago, while new.
        let fortyDaysAgo = t0.addingTimeInterval(-40 * 86_400)
        h.add(clip("old pinned", at: fortyDaysAgo), now: fortyDaysAgo)
        h.togglePin(try #require(h.items.first).id)
        h.add(clip("old", at: t0.addingTimeInterval(-31 * 86_400)), now: t0.addingTimeInterval(-31 * 86_400))
        for i in 0..<210 { h.add(clip("item \(i)", at: t0.addingTimeInterval(Double(i))), now: t0) }
        #expect(h.items.filter { !$0.pinned }.count == 200)
        #expect(!h.items.contains { $0.content == "old" }, "older than 30 days")
        #expect(h.items.contains { $0.content == "old pinned" }, "pinned items stay")
    }

    @Test func searchMatchesTextAndApp() {
        var h = ClipHistory()
        h.add(clip("swift test", app: "Ghostty"), now: t0)
        h.add(clip("Café menu", app: "Notes"), now: t0)
        #expect(h.search("SWIFT").map(\.content) == ["swift test"])
        #expect(h.search("cafe").map(\.content) == ["Café menu"], "ignores case and accents")
        #expect(h.search("ghostty").map(\.content) == ["swift test"])
        #expect(h.search("").count == 2)
    }

    @Test func groupedByDay() {
        var cal = Calendar(identifier: .gregorian)
        cal.timeZone = TimeZone(identifier: "UTC")!
        let items = [clip("now", at: t0), clip("yesterday", at: t0.addingTimeInterval(-86_400)), clip("old", at: t0.addingTimeInterval(-3 * 86_400))]
        let groups = ClipHistory.days(items, now: t0, calendar: cal)
        #expect(groups.map(\.title).prefix(2) == ["Today", "Yesterday"] && groups.count == 3)
        #expect(groups.map { $0.items.map(\.content) } == [["now"], ["yesterday"], ["old"]])
    }

    @Test func savesAndLoads() throws {
        var h = ClipHistory()
        h.add(clip("a"), now: t0)
        let data = try JSONEncoder().encode(h)
        #expect(try JSONDecoder().decode(ClipHistory.self, from: data) == h)
    }
}
